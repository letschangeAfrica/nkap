/**
 * Builds the text of public sw.js at build time (see vite.config.js).
 * Strategy:
 *  - App shell (HTML, JS, CSS, Latin fonts, icons) is precached, so the app opens offline.
 *  - Page loads are network-first: online users always get the latest version.
 *  - Other same-origin files are cached the first time they are used.
 *  - Videos and other sites (the exchange-rate API) are never touched: the app already
 *    keeps its own copy of the last rates, and videos use range requests.
 */
export function buildServiceWorker({ version, precache }) {
  return `/* Nkap service worker ${version} (generated by sw/buildServiceWorker.js) */
const VERSION = ${JSON.stringify(version)}
const SHELL = 'nkap-shell-' + VERSION
const RUNTIME = 'nkap-runtime-' + VERSION
const PRECACHE = ${JSON.stringify(precache)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('nkap-') && k !== SHELL && k !== RUNTIME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin) return
  if (request.destination === 'video' || url.pathname.endsWith('.mp4') || request.headers.has('range')) return

  if (request.mode === 'navigate') {
    // Network first, so an online user always sees the newest version; the cached shell when offline
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && !response.redirected) {
            const copy = response.clone()
            caches.open(SHELL).then((cache) => cache.put('/', copy))
          }
          return response
        })
        .catch(() => caches.match('/', { cacheName: SHELL })),
    )
    return
  }

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone()
            caches.open(RUNTIME).then((cache) => cache.put(request, copy))
          }
          return response
        }),
    ),
  )
})
`
}

/** Which built files belong in the offline app shell. */
export function shellFiles(fileNames) {
  const wanted = (f) =>
    /\.(js|css)$/.test(f) ||
    /-latin(-ext)?-\d{3}-normal-[\w-]+\.woff2$/.test(f) // Latin fonts only; other alphabets load on demand
  return fileNames.filter(wanted).map((f) => `/${f}`)
}

